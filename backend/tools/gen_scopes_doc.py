"""Render the Graph scope table in docs/trust.md from the code.

Usage (in backend/): python -m tools.gen_scopes_doc --write
tests/test_trust_doc.py fails if docs/trust.md is out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

from app.services.microsoft_oauth_scopes import (
    DELEGATED_SCOPES,
    LICENSE_COST_CHECKER_SCOPES,
    PREVIEW_SCOPES,
    WRITE_SCOPES,
)

START = "<!-- scopes:start (generated by `python -m tools.gen_scopes_doc --write`; do not edit) -->"
END = "<!-- scopes:end -->"
TRUST_DOC = Path(__file__).resolve().parents[2] / "docs" / "trust.md"

MODES = [
    ("Full connect (connect a tenant, re-authorize)", DELEGATED_SCOPES),
    ("Preview sign-in (read-only)", PREVIEW_SCOPES),
    ("Licence cost checker", LICENSE_COST_CHECKER_SCOPES),
]


def render() -> str:
    lines = [START, "", "| Sign-in | Read scopes | Write scopes |", "|---|---|---|"]
    for label, scopes in MODES:
        reads = [s for s in scopes if s not in WRITE_SCOPES]
        writes = [s for s in scopes if s in WRITE_SCOPES]
        lines.append(
            f"| {label} | {', '.join(f'`{s}`' for s in reads)} | "
            f"{', '.join(f'**`{s}`**' for s in writes) or 'none'} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def replace_block(text: str) -> str:
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + render() + tail


if __name__ == "__main__":
    current = TRUST_DOC.read_text(encoding="utf-8")
    updated = replace_block(current)
    if "--write" in sys.argv:
        TRUST_DOC.write_text(updated, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(render() + "\n")
