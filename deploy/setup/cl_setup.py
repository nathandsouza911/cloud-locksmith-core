"""One-shot setup for a local Cloud Locksmith: app registration plus config file.

Run it through `docker compose run --rm setup` in deploy/. It signs in with a device
code, creates a single-tenant app registration with the delegated Graph scopes the
backend asks for, creates a 24-month client secret, generates the local secrets and
writes deploy/cloud-locksmith.env. It never grants admin consent, never assigns roles,
never prints a secret and never replaces a config that already exists.

`--rotate-secret` adds a new client secret, saves it, then deletes the old one.

Exit codes: 0 success or status, 1 failure, 2 an existing config is incomplete.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import secrets
import subprocess
import sys
import tempfile
from pathlib import Path

from microsoft_oauth_scopes import DELEGATED_SCOPES

CONFIG_NAME = "cloud-locksmith.env"
GRAPH_APP_ID = "00000003-0000-0000-c000-000000000000"
PERSONAL_ACCOUNT_TENANT = "9188040d-6c67-4c5b-b112-36a304b66dad"
APP_DISPLAY_NAME = "Cloud Locksmith (local)"
SIGN_IN_AUDIENCE = "AzureADMyOrg"
BACKEND_URL = "http://localhost:8000"
FRONTEND_URL = "http://localhost:3000"
REDIRECT_URI = f"{BACKEND_URL}/api/v1/auth/microsoft/callback"
SECRET_YEARS = "2"
SECRET_DISPLAY_NAME = "setup"
HEADER = "# Generated by setup. Do not commit. Do not edit the secrets.\n"

SECRET_KEYS = ("MICROSOFT_CLIENT_SECRET", "MICROSOFT_CLIENT_SECRET_KEY_ID", "MICROSOFT_CLIENT_SECRET_EXPIRES")
REQUIRED_KEYS: tuple[str, ...] = (
    "ENVIRONMENT",
    "LOCAL_LOOPBACK_ONLY",
    "MICROSOFT_TENANT",
    "ENABLE_SCHEDULER",
    "ENABLE_AUTO_REMEDIATION",
    "MICROSOFT_CLIENT_ID",
    *SECRET_KEYS,
    "MICROSOFT_REDIRECT_URI",
    "BACKEND_PUBLIC_URL",
    "FRONTEND_URL",
    "CORS_ALLOWED_ORIGINS",
    "SESSION_SECRET",
    "APP_JWT_SECRET",
    "REPORT_SIGNING_SECRET",
    "ENCRYPTION_KEY",
    "POSTGRES_PASSWORD",
    "REDIS_PASSWORD",
    "DATABASE_URL",
    "REDIS_HOST",
    "REDIS_PORT",
)

_GUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
_KEY = re.compile(r"[A-Z][A-Z0-9_]*")
# Compose and pydantic read the file unquoted, so a value must need no quoting.
_NEEDS_QUOTING = re.compile(r"[\s$\"'`\\#]")
_SECRET_FIELD = re.compile(
    r"""(?ix)
    ( ["']?[\w-]*(?:password|secret)[\w-]*["']? \s* [:=] \s* )   # "password": / secret=
    ( "[^"]*" | '[^']*' | [^\s,}]+ )
    """
)
_SECRET_FLAG = re.compile(r"(?i)(--?[\w-]*(?:password|secret)[\w-]*\s+)(\S+)")


class AzError(Exception):
    """An `az` command exited non-zero. The message never holds a secret value."""


def redact(text: str) -> str:
    text = _SECRET_FIELD.sub(r"\1<redacted>", text)
    return _SECRET_FLAG.sub(r"\1<redacted>", text)


def run_az(args: list[str], *, capture: bool = True) -> object:
    """Run `az`; return its parsed JSON output. stdout is never printed.

    `capture=False` is only for the device-code sign-in, whose prompt the user must see.
    """
    if not capture:
        result = subprocess.run(["az", *args, "-o", "none"])
        if result.returncode != 0:
            raise AzError(f"az {args[0]} exited with status {result.returncode}")
        return None
    result = subprocess.run(["az", *args, "-o", "json"], capture_output=True, text=True)
    if result.returncode != 0:
        command = redact(" ".join(["az", *args[:4]]))
        raise AzError(f"{command} failed: {redact(result.stderr.strip())}")
    return json.loads(result.stdout) if result.stdout.strip() else None


def generate_local_secrets() -> dict[str, str]:
    while True:
        signing = {
            key: secrets.token_urlsafe(48) for key in ("SESSION_SECRET", "APP_JWT_SECRET", "REPORT_SIGNING_SECRET")
        }
        if len(set(signing.values())) == len(signing):
            break
    return {
        **signing,
        # A Fernet key is 32 random bytes, url-safe base64 encoded.
        "ENCRYPTION_KEY": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
        "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
        "REDIS_PASSWORD": secrets.token_urlsafe(32),
    }


def build_config(
    *,
    tenant_id: str,
    client_id: str,
    client_secret: str,
    secret_key_id: str,
    secret_expires: str,
    local: dict[str, str],
) -> dict[str, str]:
    if not _GUID.fullmatch(tenant_id):
        raise ValueError("the tenant ID is not a GUID")
    if local["REPORT_SIGNING_SECRET"] == local["APP_JWT_SECRET"]:
        raise ValueError("REPORT_SIGNING_SECRET must differ from APP_JWT_SECRET")
    values = {
        "ENVIRONMENT": "production",
        "LOCAL_LOOPBACK_ONLY": "true",
        "MICROSOFT_TENANT": tenant_id,
        "ENABLE_SCHEDULER": "false",
        "ENABLE_AUTO_REMEDIATION": "false",
        "MICROSOFT_CLIENT_ID": client_id,
        "MICROSOFT_CLIENT_SECRET": client_secret,
        "MICROSOFT_CLIENT_SECRET_KEY_ID": secret_key_id,
        "MICROSOFT_CLIENT_SECRET_EXPIRES": secret_expires,
        "MICROSOFT_REDIRECT_URI": REDIRECT_URI,
        "BACKEND_PUBLIC_URL": BACKEND_URL,
        "FRONTEND_URL": FRONTEND_URL,
        "CORS_ALLOWED_ORIGINS": FRONTEND_URL,
        **{key: local[key] for key in ("SESSION_SECRET", "APP_JWT_SECRET", "REPORT_SIGNING_SECRET")},
        "ENCRYPTION_KEY": local["ENCRYPTION_KEY"],
        "POSTGRES_PASSWORD": local["POSTGRES_PASSWORD"],
        "REDIS_PASSWORD": local["REDIS_PASSWORD"],
        "DATABASE_URL": f"postgresql://cloudlocksmith:{local['POSTGRES_PASSWORD']}@postgres:5432/cloudlocksmith",
        "REDIS_HOST": "redis",
        "REDIS_PORT": "6379",
    }
    return {key: values[key] for key in REQUIRED_KEYS}


def _env_line(key: str, value: str) -> str:
    if not _KEY.fullmatch(key):
        raise ValueError(f"invalid config key {key!r}")
    if _NEEDS_QUOTING.search(value):
        raise ValueError(f"the value of {key} contains a character the env file cannot hold unquoted")
    return f"{key}={value}\n"


def render_env(config: dict[str, str]) -> str:
    return HEADER + "".join(_env_line(key, value) for key, value in config.items())


def parse_env(text: str) -> dict[str, str]:
    config: dict[str, str] = {}
    for number, line in enumerate(text.split("\n"), start=1):
        if not line.strip() or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep or not _KEY.fullmatch(key):
            raise ValueError(f"line {number} is not KEY=value")
        config[key] = value
    return config


def missing_keys(config: dict[str, str]) -> list[str]:
    return [key for key in REQUIRED_KEYS if not config.get(key)]


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    try:
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        try:
            os.chmod(tmp, 0o600)
        except OSError:
            pass  # filesystem without POSIX modes
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def write_config(path: Path, config: dict[str, str]) -> None:
    if path.exists():
        raise FileExistsError(f"{path} already exists")
    _atomic_write(path, render_env(config))


def replace_secret(path: Path, *, client_secret: str, secret_key_id: str, secret_expires: str) -> None:
    """Rewrite only the three client-secret lines; every other byte stays the same."""
    new = {
        "MICROSOFT_CLIENT_SECRET": client_secret,
        "MICROSOFT_CLIENT_SECRET_KEY_ID": secret_key_id,
        "MICROSOFT_CLIENT_SECRET_EXPIRES": secret_expires,
    }
    lines = path.read_bytes().decode("utf-8").split("\n")
    seen = set()
    for index, line in enumerate(lines):
        key = line.partition("=")[0]
        if key in new and not line.startswith("#"):
            lines[index] = _env_line(key, new[key])[:-1]
            seen.add(key)
    if seen != set(new):
        raise ValueError(f"{path.name} has no line for {', '.join(sorted(set(new) - seen))}")
    _atomic_write(path, "\n".join(lines))


def required_resource_access(scope_names: list[str], graph_scopes: list[dict]) -> dict:
    ids = {scope["value"]: scope["id"] for scope in graph_scopes}
    unknown = [name for name in scope_names if name not in ids]
    if unknown:
        raise ValueError(f"Microsoft Graph does not list these delegated scopes: {', '.join(unknown)}")
    return {
        "resourceAppId": GRAPH_APP_ID,
        "resourceAccess": [{"id": ids[name], "type": "Scope"} for name in scope_names],
    }


def _error(message: str) -> None:
    print(message, file=sys.stderr)


def _load(path: Path) -> tuple[dict[str, str] | None, int | None]:
    """Return (config, None) for a complete config, (None, None) if there is none,
    or (None, exit code) after reporting an incomplete one."""
    if not path.exists():
        return None, None
    try:
        config = parse_env(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        _error(f"{path.name} exists but cannot be read ({exc}). It was left unchanged.")
        return None, 2
    missing = missing_keys(config)
    if missing:
        _error(
            f"{path.name} exists but is incomplete (perhaps an earlier run was interrupted).\n"
            f"Missing: {', '.join(missing)}\n"
            "Setup does not overwrite an existing config. If no stack has used it yet, move it\n"
            "aside, delete the 'Cloud Locksmith (local)' app registration if one was created,\n"
            "and run setup again."
        )
        return None, 2
    return config, None


def _sign_in(az) -> None:
    print("Sign in with a work account that can register applications in your Microsoft 365 tenant.")
    try:
        az(["login", "--use-device-code", "--allow-no-subscriptions"], capture=False)
    except AzError as exc:
        raise AzError(f"Sign-in failed or was cancelled ({exc}). Nothing was created.") from None


def _sign_out(az) -> None:
    try:
        az(["logout"])
    except AzError:
        pass


def _new_secret(az, app_id: str) -> tuple[str, str, str]:
    """Append a 24-month client secret; return (secret, key ID, expiry)."""
    before = {cred["keyId"] for cred in az(["ad", "app", "credential", "list", "--id", app_id])}
    result = az(
        [
            "ad",
            "app",
            "credential",
            "reset",
            "--id",
            app_id,
            "--append",
            "--years",
            SECRET_YEARS,
            "--display-name",
            SECRET_DISPLAY_NAME,
        ]
    )
    password = result["password"]
    added = [cred for cred in az(["ad", "app", "credential", "list", "--id", app_id]) if cred["keyId"] not in before]
    if len(added) != 1:
        raise AzError("could not identify the new client secret in the credential list")
    return password, added[0]["keyId"], added[0]["endDateTime"]


def _is_forbidden(exc: AzError) -> bool:
    text = str(exc)
    return any(marker in text for marker in ("Insufficient privileges", "Authorization_RequestDenied", "Forbidden"))


def _status(config: dict[str, str]) -> int:
    print(
        "Cloud Locksmith is already set up.\n"
        f"  Tenant ID:             {config['MICROSOFT_TENANT']}\n"
        f"  Client ID:             {config['MICROSOFT_CLIENT_ID']}\n"
        f"  Client secret expires: {config['MICROSOFT_CLIENT_SECRET_EXPIRES']}\n"
        "Start it with: docker compose up -d\n"
        "Rotate the client secret with: docker compose run --rm setup --rotate-secret"
    )
    return 0


def _signed_in_tenant(az) -> str:
    return str(az(["account", "show"])["tenantId"]).lower()


def _create(path: Path, az) -> int:
    _sign_in(az)
    try:
        tenant_id = _signed_in_tenant(az)
        if tenant_id == PERSONAL_ACCOUNT_TENANT:
            _error(
                "This is a personal Microsoft account. Sign in with a work account in the "
                "Microsoft 365 tenant you want to scan. Nothing was created."
            )
            return 1
        graph_scopes = az(["ad", "sp", "show", "--id", GRAPH_APP_ID, "--query", "oauth2PermissionScopes"])
        resource_access = required_resource_access(DELEGATED_SCOPES, graph_scopes)
        local = generate_local_secrets()
        with tempfile.TemporaryDirectory() as scratch:
            access_file = Path(scratch) / "required-resource-accesses.json"
            access_file.write_text(json.dumps([resource_access]), encoding="utf-8")
            try:
                app = az(
                    [
                        "ad",
                        "app",
                        "create",
                        "--display-name",
                        APP_DISPLAY_NAME,
                        "--sign-in-audience",
                        SIGN_IN_AUDIENCE,
                        "--web-redirect-uris",
                        REDIRECT_URI,
                        "--required-resource-accesses",
                        f"@{access_file}",
                    ]
                )
            except AzError as exc:
                if _is_forbidden(exc):
                    _error(
                        "Your account is not allowed to register applications in this tenant. Sign in as a "
                        "Global Administrator, Application Administrator or Cloud Application Administrator, "
                        "or ask one to run setup. Nothing was created."
                    )
                else:
                    _error(f"Creating the app registration failed: {exc}\nNothing was created.")
                return 1
        app_id = app["appId"]
        try:
            az(["ad", "sp", "create", "--id", app_id])
            client_secret, key_id, expires = _new_secret(az, app_id)
            config = build_config(
                tenant_id=tenant_id,
                client_id=app_id,
                client_secret=client_secret,
                secret_key_id=key_id,
                secret_expires=expires,
                local=local,
            )
            write_config(path, config)
        except (Exception, KeyboardInterrupt) as exc:
            _error(f"Setup failed after creating the app registration: {redact(str(exc))}")
            try:
                az(["ad", "app", "delete", "--id", app_id])
                _error(f"The app registration {app_id} was deleted and no config was written; run setup again.")
            except AzError:
                _error(
                    f"Deleting the app registration {app_id} also failed. Delete '{APP_DISPLAY_NAME}' in the "
                    "Entra admin center (App registrations), then run setup again."
                )
            return 1
    finally:
        _sign_out(az)
    print(
        "\nSetup finished. The config is in deploy/cloud-locksmith.env; keep it private.\n"
        f"  Tenant ID:             {tenant_id}\n"
        f"  Client ID:             {app_id}\n"
        f"  Client secret expires: {expires}\n"
        "\nNext steps, in deploy/:\n"
        "  1. docker compose up -d\n"
        f"  2. Open {FRONTEND_URL}\n"
        "  3. Sign in with Preview first (read-only).\n"
        "\nOn a VM, reach it from your own machine through an SSH tunnel:\n"
        "  ssh -L 3000:localhost:3000 -L 8000:localhost:8000 <user>@<vm>"
    )
    return 0


def _rotate(path: Path, config: dict[str, str], az) -> int:
    app_id = config["MICROSOFT_CLIENT_ID"]
    old_key_id = config["MICROSOFT_CLIENT_SECRET_KEY_ID"]
    _sign_in(az)
    try:
        tenant_id = _signed_in_tenant(az)
        if tenant_id != config["MICROSOFT_TENANT"].lower():
            _error(
                f"You signed in to tenant {tenant_id}, but this config is for tenant "
                f"{config['MICROSOFT_TENANT']}. Sign in to that tenant. Nothing was changed."
            )
            return 1
        client_secret, key_id, expires = _new_secret(az, app_id)
        try:
            replace_secret(path, client_secret=client_secret, secret_key_id=key_id, secret_expires=expires)
        except (Exception, KeyboardInterrupt) as exc:
            _error(f"Saving the new client secret failed: {redact(str(exc))}")
            try:
                az(["ad", "app", "credential", "delete", "--id", app_id, "--key-id", key_id])
                _error("The new secret was deleted; the config and the old secret are unchanged.")
            except AzError:
                _error(f"Also delete the unused client secret with key ID {key_id} in the Entra admin center.")
            return 1
        try:
            az(["ad", "app", "credential", "delete", "--id", app_id, "--key-id", old_key_id])
            old_deleted = True
        except AzError:
            old_deleted = False
    finally:
        _sign_out(az)
    print(f"The new client secret is saved. It expires {expires}.")
    print("Apply it with: docker compose up -d --force-recreate")
    if not old_deleted:
        _error(
            f"Deleting the old client secret failed. The new secret is saved and in use after the restart.\n"
            f"Delete the old secret with key ID {old_key_id} in the Entra admin center: App registrations > "
            f"{APP_DISPLAY_NAME} > Certificates & secrets."
        )
        return 1
    print("The old client secret was deleted.")
    return 0


def main(argv: list[str] | None = None, *, az=run_az, out_dir: Path = Path("/out")) -> int:
    parser = argparse.ArgumentParser(
        prog="setup",
        description=(
            "Create the Cloud Locksmith app registration in your Microsoft 365 tenant and write "
            "deploy/cloud-locksmith.env. With an existing config it only prints its status."
        ),
    )
    parser.add_argument(
        "--rotate-secret",
        action="store_true",
        help="add a new 24-month client secret, save it, then delete the old one",
    )
    args = parser.parse_args(argv)

    if not out_dir.is_dir() or not os.access(out_dir, os.W_OK):
        _error(f"{out_dir} is not a writable directory. Run this as: docker compose run --rm setup (in deploy/).")
        return 1
    path = out_dir / CONFIG_NAME
    config, code = _load(path)
    if code is not None:
        return code
    try:
        if args.rotate_secret:
            if config is None:
                _error(f"There is no {CONFIG_NAME} to rotate. Run: docker compose run --rm setup")
                return 1
            return _rotate(path, config, az)
        if config is not None:
            return _status(config)
        return _create(path, az)
    except AzError as exc:
        _error(str(exc))
        return 1
    except ValueError as exc:
        _error(f"Setup failed: {redact(str(exc))}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
